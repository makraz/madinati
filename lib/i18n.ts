export const STRINGS: Record<Lang, Dict> = { fr, en, ar };

export const tr = (lang: Lang, key: string, params?: Record<string, string>): string => {
  let s = STRINGS[lang]?.[key] ?? fr[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, v);
  return s;
};
